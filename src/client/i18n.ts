export type Locale = "en" | "zh-CN" | "es" | "ja";
export type LanguagePreference = Locale | "auto";

export interface LocaleOption {
  label: string;
  locale: Locale;
}

export const languageStorageKey = "secure-p2p-transfer:locale";

export const localeOptions: LocaleOption[] = [
  { locale: "en", label: "English" },
  { locale: "zh-CN", label: "简体中文" },
  { locale: "es", label: "Español" },
  { locale: "ja", label: "日本語" },
];

export function resolveLocale(candidate: string | null | undefined): Locale {
  return resolveLocaleCandidate(candidate) ?? "en";
}

export function resolveLocaleFromLanguages(candidates: readonly string[] | string | null | undefined): Locale {
  const languages = Array.isArray(candidates) ? candidates : [candidates];
  for (const language of languages) {
    const locale = resolveLocaleCandidate(language);
    if (locale) {
      return locale;
    }
  }

  return "en";
}

export function resolveLanguagePreference(candidate: string | null | undefined): LanguagePreference {
  if (!candidate) {
    return "auto";
  }

  if (candidate.toLowerCase() === "auto") {
    return "auto";
  }

  return resolveLocale(candidate);
}

function resolveLocaleCandidate(candidate: string | null | undefined): Locale | undefined {
  if (!candidate) {
    return undefined;
  }

  const normalized = candidate.toLowerCase();
  if (normalized.startsWith("zh")) {
    return "zh-CN";
  }

  if (normalized.startsWith("es")) {
    return "es";
  }

  if (normalized.startsWith("ja")) {
    return "ja";
  }

  return undefined;
}

